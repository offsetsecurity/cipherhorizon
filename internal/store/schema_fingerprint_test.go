package store

import (
	"database/sql"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

var updateSchema = flag.Bool("update-schema", false, "rewrite schema_fingerprint.go and testdata/schema.txt from the current migrations")

const schemaDump = "testdata/schema.txt"

// TestSchemaFingerprint keeps the compiled-in fingerprint, and the readable dump reviewers diff, in
// step with the migrations. After adding a migration: go test ./internal/store -run TestSchemaFingerprint -update-schema
func TestSchemaFingerprint(t *testing.T) {
	s, err := Open(filepath.Join(t.TempDir(), "fresh.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer s.Close() //nolint:errcheck // test
	sum, lines, err := schemaFingerprint(s.db)
	if err != nil {
		t.Fatal(err)
	}
	dump := strings.Join(lines, "\n") + "\n"
	if *updateSchema {
		src := fmt.Sprintf(`// Code generated by "go test ./internal/store -run TestSchemaFingerprint -update-schema"; DO NOT EDIT.

package store

// schemaFingerprintWant is the fingerprint of the schema this program's migrations build (see
// schemaFingerprint). testdata/schema.txt is the same schema, readable.
const schemaFingerprintWant = %q
`, sum)
		if err := os.WriteFile("schema_fingerprint.go", []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(schemaDump, []byte(dump), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if sum != schemaFingerprintWant {
		t.Errorf("the schema changed (fingerprint %s, compiled in %q). Run: go test ./internal/store -run TestSchemaFingerprint -update-schema, and review the diff of %s", sum, schemaFingerprintWant, schemaDump)
	}
	want, err := os.ReadFile(schemaDump)
	if err != nil {
		t.Fatal(err)
	}
	if strings.ReplaceAll(string(want), "\r\n", "\n") != dump {
		t.Errorf("%s is out of date; regenerate it with -update-schema", schemaDump)
	}
}

// The fingerprint sees the changes that matter and ignores the spelling of the SQL.
func TestSchemaFingerprintSeesStructure(t *testing.T) {
	base, _, err := fingerprintOf(t, `CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT NOT NULL DEFAULT '')`)
	if err != nil {
		t.Fatal(err)
	}
	same, _, _ := fingerprintOf(t, "CREATE TABLE t (\n\ta INTEGER PRIMARY KEY,\n\tb TEXT NOT NULL DEFAULT ''\n)")
	if same != base {
		t.Error("whitespace in the SQL changed the fingerprint")
	}
	for name, ddl := range map[string]string{
		"a new column":       `CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT NOT NULL DEFAULT '', c INTEGER)`,
		"another default":    `CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT NOT NULL DEFAULT 'x')`,
		"nullable":           `CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT DEFAULT '')`,
		"an index":           `CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT NOT NULL DEFAULT ''); CREATE INDEX t_b ON t(b)`,
		"a partial index":    `CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT NOT NULL DEFAULT ''); CREATE INDEX t_b ON t(b) WHERE b <> ''`,
		"a trigger":          `CREATE TABLE t (a INTEGER PRIMARY KEY, b TEXT NOT NULL DEFAULT ''); CREATE TRIGGER t_no BEFORE DELETE ON t BEGIN SELECT RAISE(ABORT, 'no'); END`,
		"another table name": `CREATE TABLE u (a INTEGER PRIMARY KEY, b TEXT NOT NULL DEFAULT '')`,
	} {
		got, _, err := fingerprintOf(t, ddl)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if got == base {
			t.Errorf("%s did not change the fingerprint", name)
		}
	}
}

func fingerprintOf(t *testing.T, ddl string) (string, []string, error) {
	t.Helper()
	db, err := openReadWriteForTest(filepath.Join(t.TempDir(), "x.db"))
	if err != nil {
		return "", nil, err
	}
	defer db.Close() //nolint:errcheck // test
	if _, err := db.Exec(ddl); err != nil {
		return "", nil, err
	}
	return schemaFingerprint(db)
}

func openReadWriteForTest(path string) (*sql.DB, error) {
	return sql.Open("sqlite", "file:"+path)
}
