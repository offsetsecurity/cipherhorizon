// The weak-key rules report what the scan's key tests proved (internal/weakkey): a key that can be
// broken from its public half alone. The scan runs the tests on every certificate the server
// sends and on every SSH host key; the rules only read the result. A report made before the tests
// existed carries none, and its checks are "not checked", never "passed".

var (
	citROCA = Citation{Title: "CVE-2017-15361 (ROCA): Infineon RSALib generates RSA keys that can be factored; Nemec et al., \"The Return of Coppersmith's Attack\", CCS 2017",
		URL: "https://nvd.nist.gov/vuln/detail/CVE-2017-15361"}
	citFermat = Citation{Title: "CVE-2022-26320 (Böck, \"Fermat Factorization in the Wild\", 2023): RSA keys whose two primes are close together",
		URL: "https://nvd.nist.gov/vuln/detail/CVE-2022-26320"}
	citKeyGen = Citation{Title: "NIST FIPS 186-5: Digital Signature Standard (key-pair generation: RSA primes, Appendix A.1; elliptic-curve private keys, Appendix A.2)",
		URL: "https://csrc.nist.gov/pubs/fips/186-5/final"}
)

type weakKeyRule struct {
	id, title, sshTitle string
	kind                weakkey.Kind
	severity            Severity
	citations           []Citation
	why                 string
	pass                string
}

var weakKeyRules = []weakKeyRule{
	{"KEY.EC-SMALL-SCALAR", "A certificate's private key can be found by search", "A host key's private key can be found by search",
		weakkey.ECSmallScalar, Critical, []Citation{citKeyGen, citCAKeyCompromise},
		"The private half of this elliptic-curve key is a small number. Anyone can compute it and sign as the key's owner.",
		"No elliptic-curve key on the served chain has a private key small enough to find by search"},
	{"KEY.RSA-SMALL-FACTOR", "An RSA key has a small factor", "An RSA host key has a small factor",
		weakkey.RSASmallFactor, Critical, []Citation{citKeyGen},
		"An RSA modulus must be the product of two large primes. One with a small factor is malformed or corrupted, and offers no security.",
		"No RSA key on the served chain is divisible by a prime below 65536"},
	{"KEY.RSA-CLOSE-PRIMES", "An RSA key's two primes are too close together", "An RSA host key's two primes are too close together",
		weakkey.RSAClosePrimes, Critical, []Citation{citFermat, citKeyGen},
		"When the two primes are close, Fermat's method recovers them in moments, and with them the private key.",
		"No RSA key on the served chain has primes close enough for Fermat's method"},
	{"KEY.RSA-ROCA", "An RSA key has the ROCA defect", "An RSA host key has the ROCA defect",
		weakkey.RSAROCA, High, []Citation{citROCA},
		"Keys generated by Infineon's RSALib (smart cards, TPMs, tokens made before late 2017) can be factored at practical cost.",
		"No RSA key on the served chain has the ROCA fingerprint"},
}

const (
	weakKeyFixTLS = "Generate a new key pair on a system you trust, with a current library, and have the certificate reissued; then revoke the old certificate. If the key belongs to a CA above your certificate, move to a different CA and report the key to it."
	weakKeyFixSSH = "Generate a new host key (ssh-keygen -t ed25519), replace the HostKey file, restart sshd, and tell clients to expect the new fingerprint."
)

func hasWeak(kt *tlsprobe.KeyTests, kind weakkey.Kind) (string, bool) {
	if kt == nil {
		return "", false
	}
	for _, w := range kt.Weak {
		if w.Kind == kind {
			return w.Detail, true
		}
	}
	return "", false
}

// keyTestsRan reports whether the report carries weak-key test results at all.
func keyTestsRan(rep *tlsprobe.Report) bool {
	for _, cr := range rep.Certificates {
		for _, ci := range cr.Chain {
			if ci.KeyTests != nil {
				return true
			}
		}
	}
	return false
}

func tlsWeakKeyRules() []rule {
	var out []rule
	for _, wr := range weakKeyRules {
		out = append(out, rule{id: wr.id, title: wr.title, category: "certificate", severity: wr.severity, evidence: Observed,
			citations: wr.citations, remediation: weakKeyFixTLS + " " + wr.why,
			check: func(c *ctx) []hit {
				var hits []hit
				seen := map[string]bool{}
				for _, cr := range c.rep.Certificates {
					for i, ci := range cr.Chain {
						detail, ok := hasWeak(ci.KeyTests, wr.kind)
						if !ok || seen[ci.SHA256] {
							continue
						}
						seen[ci.SHA256] = true
						what := "the server's certificate " + ci.Subject
						if i > 0 || ci.IsCA {
							what = "the CA certificate " + ci.Subject
						}
						hits = append(hits, hit{detail: fmt.Sprintf("%s (%s %s): %s", what, ci.PublicKey.Algorithm, keySize(ci.PublicKey), detail)})
					}
				}
				return hits
			}})
	}
	return out
}

// weakKeyCheck reports whether an SSH check ID is one of the weak-key checks.
func weakKeyCheck(id string) bool {
	for _, wr := range weakKeyRules {
		if id == strings.Replace(wr.id, "KEY.", "SSH.HOSTKEY-", 1) {
			return true
		}
	}
	return false
}

func keySize(k tlsprobe.KeyInfo) string {
	if k.Curve != "" {
		return k.Curve
	}
	if k.Bits > 0 {
		return fmt.Sprintf("%d bits", k.Bits)
	}
	return "key"
}

// sshKeyTestsRan reports whether the SSH report carries weak-key test results.
func sshKeyTestsRan(keys []sshprobe.HostKey) bool {
	for _, k := range keys {
		if k.KeyTests != nil {
			return true
		}
	}
	return false
}

func init() {
	sshRules = append(sshRules, sshWeakKeyRules()...)
	for _, wr := range weakKeyRules {
		passText[wr.id] = wr.pass
		passText[strings.Replace(wr.id, "KEY.", "SSH.HOSTKEY-", 1)] = strings.Replace(wr.pass, "key on the served chain", "host key", 1)
	}
}

func sshWeakKeyRules() []sshRule {
	var out []sshRule
	for _, wr := range weakKeyRules {
		out = append(out, sshRule{id: strings.Replace(wr.id, "KEY.", "SSH.HOSTKEY-", 1), title: wr.sshTitle, category: "host-key",
			severity: wr.severity, evidence: Observed, citations: wr.citations, remediation: weakKeyFixSSH + " " + wr.why,
			check: func(c *sshCtx) []hit {
				var hits []hit
				for _, k := range c.rep.HostKeys {
					if detail, ok := hasWeak(k.KeyTests, wr.kind); ok {
						hits = append(hits, hit{detail: fmt.Sprintf("%s host key %s: %s.", k.Type, k.Fingerprint, detail)})
					}
				}
				return hits
			}})
	}
	return out
}
